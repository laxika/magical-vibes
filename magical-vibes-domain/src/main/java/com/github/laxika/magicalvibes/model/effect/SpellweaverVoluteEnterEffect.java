package com.github.laxika.magicalvibes.model.effect;

import com.github.laxika.magicalvibes.model.CardType;
import com.github.laxika.magicalvibes.model.GraveyardSearchScope;
import com.github.laxika.magicalvibes.model.filter.CardTypePredicate;

/** Marks Spellweaver Volute's graveyard-card attachment on entering the battlefield. */
public record SpellweaverVoluteEnterEffect() implements CardEffect {

    @Override
    public TargetSpec targetSpec() {
        return TargetSpec.benign(TargetPredicates.graveyardCards(
                new CardTypePredicate(CardType.INSTANT), GraveyardSearchScope.ALL_GRAVEYARDS));
    }
}
