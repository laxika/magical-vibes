package com.github.laxika.magicalvibes.cards.s;

import com.github.laxika.magicalvibes.cards.CardRegistration;
import com.github.laxika.magicalvibes.model.ActivatedAbility;
import com.github.laxika.magicalvibes.model.Card;
import com.github.laxika.magicalvibes.model.CardColor;
import com.github.laxika.magicalvibes.model.CardSubtype;
import com.github.laxika.magicalvibes.model.EffectSlot;
import com.github.laxika.magicalvibes.model.Keyword;
import com.github.laxika.magicalvibes.model.effect.CreateTokenEffect;
import com.github.laxika.magicalvibes.model.effect.GrantActivatedAbilityEffect;
import com.github.laxika.magicalvibes.model.effect.GrantScope;
import com.github.laxika.magicalvibes.model.filter.TargetFilters;

import java.util.List;
import java.util.Set;

@CardRegistration(set = "C13", collectorNumber = "171")
public class SpawningGrounds extends Card {

    public SpawningGrounds() {
        target(TargetFilters.land())
                .addEffect(EffectSlot.STATIC, new GrantActivatedAbilityEffect(
                        new ActivatedAbility(
                                true,
                                null,
                                List.of(new CreateTokenEffect(
                                        "Beast",
                                        5,
                                        5,
                                        CardColor.GREEN,
                                        List.of(CardSubtype.BEAST),
                                        Set.of(Keyword.TRAMPLE),
                                        Set.of()
                                )),
                                "{T}: Create a 5/5 green Beast creature token with trample."
                        ),
                        GrantScope.ENCHANTED_PERMANENT
                ));
    }
}
