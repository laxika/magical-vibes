package com.github.laxika.magicalvibes.cards.p;

import com.github.laxika.magicalvibes.model.Card;
import com.github.laxika.magicalvibes.model.amount.CountScope;
import com.github.laxika.magicalvibes.model.amount.PermanentCount;
import com.github.laxika.magicalvibes.model.effect.DynamicStaticBoostEffect;
import com.github.laxika.magicalvibes.model.effect.GrantScope;
import com.github.laxika.magicalvibes.model.filter.PermanentAnyOfPredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentIsArtifactPredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentIsEnchantmentPredicate;

import java.util.List;

public class PortraitOfMichiko extends Card {

    public PortraitOfMichiko() {
        PermanentCount artifactsAndEnchantmentsYouControl = new PermanentCount(
                new PermanentAnyOfPredicate(List.of(
                        new PermanentIsArtifactPredicate(),
                        new PermanentIsEnchantmentPredicate())),
                CountScope.CONTROLLER);
        addStaticEffect(new DynamicStaticBoostEffect(
                        artifactsAndEnchantmentsYouControl, artifactsAndEnchantmentsYouControl, GrantScope.SELF));
    }
}
