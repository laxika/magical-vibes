package com.github.laxika.magicalvibes.cards.h;

import com.github.laxika.magicalvibes.cards.CardRegistration;
import com.github.laxika.magicalvibes.model.Card;
import com.github.laxika.magicalvibes.model.CardType;
import com.github.laxika.magicalvibes.model.LibrarySearchDestination;
import com.github.laxika.magicalvibes.model.effect.EachPlayerSearchesLibraryEffect;
import com.github.laxika.magicalvibes.model.effect.Subjects;
import com.github.laxika.magicalvibes.model.filter.CardTypePredicate;
import com.github.laxika.magicalvibes.model.trigger.ObjectRelation;
import com.github.laxika.magicalvibes.model.trigger.Triggers;

@CardRegistration(set = "MMQ", collectorNumber = "194")
public class HiredGiant extends Card {

    public HiredGiant() {
        addTrigger(Triggers.enters(ObjectRelation.THIS), EachPlayerSearchesLibraryEffect.maySearch(
                Subjects.eachOpponent(), new CardTypePredicate(CardType.LAND), LibrarySearchDestination.BATTLEFIELD));
    }
}
