package com.github.laxika.magicalvibes.cards.f;

import com.github.laxika.magicalvibes.cards.CardRegistration;
import com.github.laxika.magicalvibes.model.Card;
import com.github.laxika.magicalvibes.model.CardType;
import com.github.laxika.magicalvibes.model.effect.DiscardEffect;
import com.github.laxika.magicalvibes.model.effect.MayEffect;
import com.github.laxika.magicalvibes.model.effect.SacrificeSelfEffect;
import com.github.laxika.magicalvibes.model.effect.Subjects;
import com.github.laxika.magicalvibes.model.filter.CardTypePredicate;
import com.github.laxika.magicalvibes.model.trigger.ObjectRelation;
import com.github.laxika.magicalvibes.model.trigger.Triggers;

@CardRegistration(set = "WTH", collectorNumber = "126")
public class FallowWurm extends Card {

    public FallowWurm() {
        addTrigger(Triggers.enters(ObjectRelation.THIS), new MayEffect(DiscardEffect.matching(1, Subjects.you(), new CardTypePredicate(CardType.LAND)),
                "Discard a land card? If you don't, sacrifice it.",
                new SacrificeSelfEffect()));
    }
}
