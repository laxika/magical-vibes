package com.github.laxika.magicalvibes.cards.n;

import com.github.laxika.magicalvibes.cards.CardRegistration;
import com.github.laxika.magicalvibes.model.Card;
import com.github.laxika.magicalvibes.model.EffectSlot;
import com.github.laxika.magicalvibes.model.condition.ControlsPermanent;
import com.github.laxika.magicalvibes.model.effect.BoostSelfEffect;
import com.github.laxika.magicalvibes.model.effect.ConditionalEffect;
import com.github.laxika.magicalvibes.model.filter.PermanentAllOfPredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentIsCreaturePredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentPowerAtLeastPredicate;

import java.util.List;

@CardRegistration(set = "HOB", collectorNumber = "78")
public class NighthowlPursuer extends Card {

    public NighthowlPursuer() {
        // Ferocious: "Whenever this creature attacks while you control a creature with power 4 or greater" —
        // "while" is not an intervening "if", so the condition is only checked when the attack trigger happens.
        addEffect(EffectSlot.ON_ATTACK, ConditionalEffect.atTriggerTime(
                new ControlsPermanent(new PermanentAllOfPredicate(List.of(
                        new PermanentIsCreaturePredicate(),
                        new PermanentPowerAtLeastPredicate(4)))),
                new BoostSelfEffect(2, 2)));
    }
}
