import com.github.laxika.magicalvibes.model.filter.PermanentIsCreaturePredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentIsSourceCardPredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentNotPredicate;
import com.github.laxika.magicalvibes.model.filter.CardAllOfPredicate;
import com.github.laxika.magicalvibes.model.filter.CardNotPredicate;
import com.github.laxika.magicalvibes.model.filter.CardSupertypePredicate;
import com.github.laxika.magicalvibes.model.filter.CardTypePredicate;
import com.github.laxika.magicalvibes.model.trigger.ActivePlayer;
import com.github.laxika.magicalvibes.model.trigger.Triggers;

import java.util.List;

@CardRegistration(set = "ONE", collectorNumber = "206")
public class KethekCrucibleGoliath extends Card {

    public KethekCrucibleGoliath() {
        // "With lesser mana value" than the sacrificed creature's: at most its mana value minus one.
        addTrigger(Triggers.endStep(ActivePlayer.YOU), new MayEffect(SequenceEffect.of(
                new SacrificePermanentsEffect(1, new PermanentAllOfPredicate(List.of(
                        new PermanentIsCreaturePredicate(),
                        new PermanentNotPredicate(new PermanentIsSourceCardPredicate()))), Subjects.you()),
                new ConditionalEffect(HappenedThisWay.sacrificed(), new RevealUntilCardPredicateRestOnBottomRandomEffect(
                        new CardAllOfPredicate(List.of(
                                new CardTypePredicate(CardType.CREATURE),
                                new CardNotPredicate(new CardSupertypePredicate(CardSupertype.LEGENDARY)),
                                new CardManaValueAtMostAmountPredicate(
                                        new Sum(AmountThisWay.sacrificedManaValue(), new Fixed(-1))))),
                        LibrarySearchDestination.BATTLEFIELD))),
                "Sacrifice another creature to reveal a nonlegendary creature with lesser mana value?"));
    }
}
