@CardRegistration(set = "BFZ", collectorNumber = "34")
public class KorBladewhirl extends Card {

    public KorBladewhirl() {
        addTrigger(Triggers.enters(Triggers.CREATURE, ObjectRelation.YOU_CONTROL),
                new TriggeringCardConditionalEffect(new CardSubtypePredicate(CardSubtype.ALLY),
                        new GrantKeywordEffect(Keyword.FIRST_STRIKE, GrantScope.ALL_OWN_CREATURES)));
    }
}
