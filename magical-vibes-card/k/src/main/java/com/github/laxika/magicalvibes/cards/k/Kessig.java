package com.github.laxika.magicalvibes.cards.k;

import com.github.laxika.magicalvibes.cards.CardRegistration;
import com.github.laxika.magicalvibes.model.Card;
import com.github.laxika.magicalvibes.model.CardSubtype;
import com.github.laxika.magicalvibes.model.Keyword;
import com.github.laxika.magicalvibes.model.effect.BoostAllOwnCreaturesEffect;
import com.github.laxika.magicalvibes.model.effect.GrantKeywordEffect;
import com.github.laxika.magicalvibes.model.effect.GrantSubtypeUntilEndOfTurnEffect;
import com.github.laxika.magicalvibes.model.effect.PreventDamageToRecipientsEffect;
import com.github.laxika.magicalvibes.model.effect.Subjects;
import com.github.laxika.magicalvibes.model.filter.PermanentAllOfPredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentHasSubtypePredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentIsCreaturePredicate;
import com.github.laxika.magicalvibes.model.filter.PermanentNotPredicate;
import com.github.laxika.magicalvibes.model.trigger.Triggers;

import java.util.List;

@CardRegistration(set = "OPC2", collectorNumber = "21")
@CardRegistration(set = "OPCA", collectorNumber = "42")
public class Kessig extends Card {

    public Kessig() {
        addStaticEffect(PreventDamageToRecipientsEffect.dealtBy(new PermanentAllOfPredicate(List.of(
                new PermanentIsCreaturePredicate(),
                new PermanentNotPredicate(new PermanentHasSubtypePredicate(CardSubtype.WEREWOLF)))))
                .combatOnly());

        addTrigger(Triggers.chaosEnsues(),
                new BoostAllOwnCreaturesEffect(2, 2),
                new GrantKeywordEffect(Keyword.TRAMPLE, Subjects.otherCreaturesYouControl()),
                new GrantSubtypeUntilEndOfTurnEffect(CardSubtype.WEREWOLF, Subjects.creaturesYouControl()));
    }
}
